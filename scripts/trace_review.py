"""M12: trace one review through every stage (README evidence), read-only, zero model calls.

source row (state/pipeline.db) → A3/A4/A5 outputs (agent_outputs) → record (grading/records.jsonl.gz) → calls
(grading/calls.jsonl.gz) → A8 verifier (evals/verify/verifier_predictions.jsonl) → membership → ranking → claims → memo /
recommendations. Writes markdown to stdout or --out.

    .venv/Scripts/python scripts/trace_review.py 8c256cff-407f-4f2c-ad6e-dabdeef1bf0d --out evals/m12/trace_ok.md
"""
import argparse
import csv
import gzip
import json
import sqlite3
import sys
from pathlib import Path


def find_jsonl_gz(path, pred):
    with gzip.open(path, "rt", encoding="utf-8") as f:
        return [r for r in map(json.loads, f) if pred(r)]


def csv_rows(path, pred=lambda r: True):
    with open(path, encoding="utf-8", newline="") as f:
        return [r for r in csv.DictReader(f) if pred(r)]


def trace(review_id, root, db):
    root = Path(root)
    out = []
    w = out.append
    conn = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row
    src = conn.execute("SELECT * FROM source_reviews WHERE review_id=?", (review_id,)).fetchone()
    if src is None:
        sys.exit(f"{review_id} not in source_reviews")
    w(f"# Trace: review `{review_id}`\n")
    w("Generated by `scripts/trace_review.py` (read-only, zero model calls).\n")
    w("## 1. Source row (A1 intake)")
    w(f"- CSV row {src['csv_row']}, rating {src['review_rating']}, likes {src['review_likes']}, "
      f"app_version {src['app_version'] or '(missing)'}, timestamp {src['review_timestamp']}")
    w(f"- scope `{src['scope']}`, scope_rank {src['scope_rank']}, text_sha256 `{src['text_sha256'][:16]}…`")
    text = src["review_text"]
    w(f"- text ({len(text)} chars): \"{text}\"\n")
    tx = conn.execute("SELECT * FROM texts WHERE text_sha256=?", (src["text_sha256"],)).fetchone()
    if tx:
        w(f"Distinct text: original_review_id `{tx['original_review_id']}`, {tx['rows_total']} row(s) share it "
          f"({tx['rows_in_scope']} in scope).\n")

    rec = find_jsonl_gz(root / "grading/records.jsonl.gz", lambda r: r["review_id"] == review_id)[0]
    cfg = rec.get("label_config")
    w("## 2. Enrichment (A3 decision → A4 router → A5 escalation → A6 extractor → A7 validator)")
    for a in conn.execute("SELECT agent, request_id, output_json FROM agent_outputs WHERE text_sha256=? "
                          "AND label_config=? ORDER BY agent", (src["text_sha256"], cfg)):
        w(f"- **{a['agent']}** (request `{a['request_id']}`): `{a['output_json'][:600]}`")
    res = conn.execute("SELECT decision_source, request_id FROM results WHERE text_sha256=? AND label_config=?",
                       (src["text_sha256"], cfg)).fetchone()
    if res:
        w(f"- result decision_source `{res['decision_source']}`")
    w(f"\nRecord in `grading/records.jsonl.gz`:\n```json\n{json.dumps(rec, indent=1, ensure_ascii=False)}\n```")
    if rec.get("evidence_quote"):
        w(f"evidence_quote is an exact substring of the text: **{rec['evidence_quote'] in text}**\n")

    w("## 3. Model calls that carried it (`grading/calls.jsonl.gz`)")
    ids = {review_id, tx["original_review_id"] if tx else review_id, rec.get("cache_source_id") or review_id}
    calls = find_jsonl_gz(root / "grading/calls.jsonl.gz", lambda c: ids & set(c.get("review_ids") or []))
    w("| request_id | agent | model | phase | outcome | reviews in call | input tok | output tok |")
    w("|---|---|---|---|---|---|---|---|")
    for c in calls:
        w(f"| `{c['request_id']}` | {c['agent']} | {c['model']} | {c['phase']} | {c['outcome']} | "
          f"{len(c['review_ids'])} | {c['input_tokens']} | {c['output_tokens']} |")
    w("")

    w("## 4. Independent verification (A8, `evals/verify/verifier_predictions.jsonl`)")
    with open(root / "evals/verify/verifier_predictions.jsonl", encoding="utf-8") as f:
        ver = [v for v in map(json.loads, f) if v["text_sha256"] == src["text_sha256"]]
    if ver:
        v = ver[0]
        w(f"- verifier ({v['verify_config']}, request `{v['request_id']}`): topic {v['topic']}, intent {v['intent']}, "
          f"severity {v['severity']}, needs_review {v['needs_review']}")
        agree = {k: v[k] == rec[k] for k in ("topic", "intent", "severity")}
        w(f"- agreement with the first labels: {agree}\n")
    else:
        w("- not in the declared 20% verification sample (or unverified)\n")

    w("## 5. Issue membership → ranking → claims → memo")
    mem = csv_rows(root / "outputs/membership.csv", lambda r: r["review_id"] == review_id)
    if not mem:
        w("- not a member (only completed complaint/cancellation records are grouped)")
    for m in mem:
        iid = m["issue_id"]
        rk = csv_rows(root / "outputs/ranking.csv", lambda r: r["issue_id"] == iid)[0]
        w(f"- `outputs/membership.csv`: issue `{iid}`")
        w(f"- `outputs/ranking.csv`: rank {rk['rank']}, complaint_count {rk['complaint_count']}, severity_sum "
          f"{rk['severity_sum']}, mean_severity {rk['mean_severity']}, priority_score {rk['priority_score']}")
        for c in csv_rows(root / "outputs/claims.csv", lambda r: r["issue_id"] == iid):
            w(f"- `outputs/claims.csv`: **{c['claim_id']}** {c['metric']} = {c['value']}")
        memo = (root / "outputs/memo.md").read_text(encoding="utf-8")
        hits = [ln.strip() for ln in memo.splitlines() if review_id in ln or f"`{iid}`" in ln]
        for h in hits[:4]:
            w(f"- `outputs/memo.md`: \"{h[:400]}{'…' if len(h) > 400 else ''}\"")
        recs = json.loads((root / "outputs/recommendations.json").read_text(encoding="utf-8"))
        for i, r in enumerate(recs.get("recommendations", []), 1):
            if review_id in json.dumps(r):
                w(f"- `outputs/recommendations.json` #{i}: **{r.get('title')}** cites this review")
    conn.close()
    return "\n".join(out) + "\n"


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("review_id")
    p.add_argument("--root", default=".")
    p.add_argument("--db", default="state/pipeline.db")
    p.add_argument("--out", type=Path)
    a = p.parse_args(argv)
    md = trace(a.review_id, a.root, a.db)
    if a.out:
        a.out.parent.mkdir(parents=True, exist_ok=True)
        a.out.write_text(md, encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
